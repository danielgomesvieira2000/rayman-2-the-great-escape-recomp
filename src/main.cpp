std::string get_game_thread_name(const OSThread* t) {
    return "rayman2-" + std::to_string(t ? t->id : 0);
}

bool select_and_report(const std::filesystem::path& path, const std::u8string& game_id) {
    switch (recomp::select_rom(path, game_id)) {
        case recomp::RomValidationError::Good:
            return true;
        case recomp::RomValidationError::FailedToOpen:
            message_box("Could not open that file.");
            return false;
        case recomp::RomValidationError::NotARom:
            message_box("That file is not an N64 ROM.");
            return false;
        case recomp::RomValidationError::IncorrectRom:
            message_box("That is an N64 ROM, but not Rayman 2 (USA).\n"
                        "This port targets NUS-NY2E rev 0, SHA-1 "
                        "50558356b059ad3fbaf5fe95380512b9dceaaf52.");
            return false;
        case recomp::RomValidationError::IncorrectVersion:
            message_box("That is Rayman 2, but not the USA revision this port targets.");
            return false;
        default:
            message_box("Could not read that ROM.");
            return false;
    }
}

