// ---------------------------------------------------------------------------
// Game registration
//
// NOT in the anonymous namespace above, and not static: RecompFrontend's
// launcher declares `extern std::vector<recomp::GameEntry> supported_games;`
// and links against this definition to list the game and drive its own
// "Load ROM" flow. Giving it internal linkage builds fine and fails at link
// with one undefined symbol and no hint as to why.
// ---------------------------------------------------------------------------

std::vector<recomp::GameEntry> supported_games = {
    recomp::GameEntry{
        .rom_hash      = kRayman2UsaRomHash,
        .internal_name = "RAYMAN 2",
        .display_name  = "Rayman 2: The Great Escape",
        .game_id       = u8"rayman2_us",
        .mod_game_id   = "rayman2",
        // The cartridge has no EEPROM, SRAM or Flash. Saves go to a Controller
        // Pak, which is an input-side accessory rather than a cartridge save
        // type, so the save type here is genuinely None.
        .save_type     = recomp::SaveType::None,
        .is_enabled    = true,
        // MUST be sign-extended. `gpr` is 64-bit, and every MIPS address the
        // runtime handles is a sign-extended 32-bit value: KSEG0 0x80000400 is
        // 0xFFFFFFFF80000400, not 0x0000000080000400.
        //
        // Writing the bare literal here cost a long debugging session. MEM_B
        // resolves a game address as rdram + (addr ^ 3) - 0xFFFFFFFF80000000,
        // so a zero-extended entrypoint yields offset 0x100000403 instead of
        // 0x403 -- exactly 0x1_00000000 too far, past the end of the 4 GB RDRAM
        // reservation and into unmapped space. librecomp's emulated IPL3 DMA
        // then wrote there and took an access violation four bytes into the
        // copy, three frames deep in the runtime, long before the entrypoint.
        //
        // N64Recomp's own generated lookup.cpp writes the same constant as
        // (gpr)(int32_t)0x80000400u for this reason; this must match it.
        .entrypoint_address = (gpr)(int32_t)0x80000400u,
        .entrypoint         = rayman2_entrypoint,
    },
};


int main(int argc, char** argv) {
    // Unbuffered, because the failure mode being chased here is a fail-fast
    // exit (0xC0000409) that discards anything still sitting in a buffer.
    std::setvbuf(stderr, nullptr, _IONBF, 0);
    std::setvbuf(stdout, nullptr, _IONBF, 0);
    std::fprintf(stderr, "[rayman2] start\n");

    // Installed before anything else: the fault being chased happens on a
    // renderer thread and otherwise produces no output at all.
    rayman2_install_crash_reporter();

    SDL_SetMainReady();

#ifdef _WIN32
    timeBeginPeriod(1);   // 1 ms scheduler granularity; the runtime sleeps in small slices
#endif

    for (const auto& game : supported_games) {
        recomp::register_game(game);
    }

    rayman2_register_sections();

    // ---- ROM ----
    // A ROM validated on a previous run and cached in the config directory wins;
    // otherwise an explicit path argument is validated and cached. The player is
    // only ever asked once.
    const std::u8string game_id = supported_games[0].game_id;
    recomp::check_all_stored_roms();
    bool have_rom = recomp::is_rom_valid(game_id);

    if (!have_rom && argc > 1) {
        have_rom = select_and_report(std::filesystem::path(argv[1]), game_id);
    }

#ifndef RAYMAN2_ENABLE_FRONTEND
    if (!have_rom) {
        message_box("No ROM configured. Pass the path to your Rayman 2 (USA) dump "
                    "as the first argument.");
        return EXIT_FAILURE;
    }

    // Without the frontend there is no launcher to start the game, so do it
    // here once the runtime is up. With the frontend, its launcher owns this
    // decision and starting from here would race it.
    // Wait for the renderer's first frame, not a fixed delay.
    //
    // ultramodern's VI thread only seeds a dummy video mode while the game has
    // not started; starting the game before its first tick makes the VI update
    // path dereference a mode that does not exist yet. A sleep here raced that
    // and lost about nine times in ten -- an access violation before librecomp
    // even initialised its heap, with the successful tenth run being the only
    // one that looked like progress.
    std::thread([game_id]() {
        using namespace std::chrono_literals;
        for (int i = 0; i < 1000 && !rayman2::vi_has_ticked().load(std::memory_order_acquire); ++i) {
            std::this_thread::sleep_for(10ms);
        }
        if (!rayman2::vi_has_ticked().load(std::memory_order_acquire)) {
            std::fprintf(stderr, "[rayman2] renderer never presented a frame; starting anyway\n");
        }
        // Load the cached ROM into memory before starting.
        //
        // This is NOT the same thing as validating it. check_all_stored_roms()
        // and is_rom_valid() only establish that a correct dump exists in the
        // config directory; they do not read it. Nothing else does either --
        // start_game() does not, and the port is expected to.
        //
        // Skipping it is not a quiet no-op. librecomp's init() emulates IPL3
        // with a fixed 1 MB DMA from ROM into RDRAM, and do_rom_read() computes
        // its source as rom.data() + physical_addr - rom_base. With an empty
        // span that is an offset from nullptr, and the copy walks into
        // unmapped memory -- an access violation on the game thread, three
        // frames deep in the runtime, with nothing pointing back at the real
        // mistake up here.
        if (!recomp::load_stored_rom(game_id)) {
            message_box("Failed to load the stored ROM from the config directory.");
            return;
        }
        std::fprintf(stderr, "[rayman2] rom loaded: %zu bytes\n",
                     recomp::get_rom().size());

        recomp::start_game(game_id, "");
    }).detach();
#else
    (void)have_rom;
#endif

    // ---- Callbacks ----
    recomp::rsp::callbacks_t rsp_callbacks{};                    // mandatory
    rsp_callbacks.get_rsp_microcode = rayman2_get_rsp_microcode;

    ultramodern::renderer::callbacks_t renderer_callbacks{};     // mandatory
    renderer_callbacks.create_render_context = rayman2::create_render_context;

    ultramodern::gfx_callbacks_t gfx_callbacks{};
    gfx_callbacks.create_gfx    = create_gfx;
    gfx_callbacks.create_window = create_window;
    gfx_callbacks.update_gfx    = update_gfx;

    ultramodern::audio_callbacks_t audio_callbacks{};
    audio_callbacks.queue_samples        = queue_samples;
    audio_callbacks.get_frames_remaining = get_frames_remaining;
    audio_callbacks.set_frequency        = set_frequency;

    ultramodern::input::callbacks_t input_callbacks{};
    input_callbacks.poll_input                = poll_input;
    input_callbacks.get_input                 = get_input;
    input_callbacks.set_rumble                = set_rumble;
    input_callbacks.get_connected_device_info = get_connected_device_info;

    ultramodern::error_handling::callbacks_t error_handling_callbacks{};
    error_handling_callbacks.message_box = message_box;

    ultramodern::threads::callbacks_t threads_callbacks{};
    threads_callbacks.get_game_thread_name = get_game_thread_name;

    recomp::Configuration config{};
    config.argc                     = argc;
    config.argv                     = argv;
    config.project_version          = kProjectVersion;
    config.rsp_callbacks            = rsp_callbacks;
    config.renderer_callbacks       = renderer_callbacks;
    config.audio_callbacks          = audio_callbacks;
    config.input_callbacks          = input_callbacks;
    config.gfx_callbacks            = gfx_callbacks;
    config.error_handling_callbacks = error_handling_callbacks;
    config.threads_callbacks        = threads_callbacks;

#ifdef RAYMAN2_ENABLE_FRONTEND
    // Program identity and menu layout must be registered before recomp::start()
    // brings the renderer up: recompui builds its menus during that bring-up.
    // The id is the directory name the frontend stores settings and saves under,
    // so it is part of the port's on-disk contract and should not drift.
    recompui::programconfig::set_program_id(u8"rayman2-recomp");
    recompui::programconfig::set_program_name("Rayman 2: The Great Escape");

    // Mandatory. recompui throws std::runtime_error during renderer bring-up if
    // no primary font has been registered by the time it builds its menus, and
    // that exception crosses a noexcept boundary -- the process fail-fasts with
    // no output whatsoever, which is a memorably unhelpful way to learn this.
    // The family name is the font's internal one, not its filename.
    recompui::register_primary_font("LatoLatin-Regular.ttf", "LatoLatin");
    recompui::register_extra_font("NotoEmoji-Regular.ttf");
#endif

    // recomp::start() brings up the renderer, and the frontend builds its menus
    // during that bring-up. Anything thrown in there crosses a noexcept
    // boundary on its way out and the process fail-fasts with no message, so
    // the exception is caught and reported here instead of being guessed at.
    rayman2_start_thread_sampler();

    std::fprintf(stderr, "[rayman2] entering recomp::start\n");
    try {
        recomp::start(config);   // blocks until the game exits
    }
    catch (const std::exception& e) {
        std::fprintf(stderr, "[rayman2] FATAL: %s\n", e.what());
        return EXIT_FAILURE;
    }
    catch (...) {
        std::fprintf(stderr, "[rayman2] FATAL: unknown exception\n");
        return EXIT_FAILURE;
    }
    rayman2_stop_thread_sampler();
    std::fprintf(stderr, "[rayman2] recomp::start returned\n");

#ifdef _WIN32
    timeEndPeriod(1);
#endif
    return EXIT_SUCCESS;
}
